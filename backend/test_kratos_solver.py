# ─────────────────────── structured rectangular mesh ───────────────────────
def structured_rect_mesh(x0, x1, y0, y1, mesh_size, id_start=1):
    """Deterministic structured right-triangle mesh of a rectangle.

    Returns (FEMMesh, next_free_node_id). Diagonal orientation alternates in a
    union-jack-free (single diagonal per cell) layout.
    """
    nx = max(1, int(round((x1 - x0) / mesh_size)))
    ny = max(1, int(round((y1 - y0) / mesh_size)))
    dx = (x1 - x0) / nx
    dy = (y1 - y0) / ny
    nodes = []
    idmap = {}
    nid = id_start
    for j in range(ny + 1):
        for i in range(nx + 1):
            idmap[(i, j)] = nid
            nodes.append(FEMNode(id=nid, x=x0 + i * dx, y=y0 + j * dy))
            nid += 1
    elements = []
    eid = 1
    for j in range(ny):
        for i in range(nx):
            n0 = idmap[(i, j)]
            n1 = idmap[(i + 1, j)]
            n2 = idmap[(i + 1, j + 1)]
            n3 = idmap[(i, j + 1)]
            elements.append(Triangle(id=eid, nodeIds=[n0, n1, n2])); eid += 1
            elements.append(Triangle(id=eid, nodeIds=[n0, n2, n3])); eid += 1
    mesh = FEMMesh(
        nodeCount=len(nodes), elementCount=len(elements),
        nodes=nodes, elements=elements,
        minAngle=45.0, maxAspectRatio=max(dx, dy) / min(dx, dy),
        meshQuality='Structured'
    )
    return mesh, nid


# ─────────────────────────────── Test 1 ───────────────────────────────
def _mindlin_series_wmax(a=4.0, q=5000.0, E=25e9, nu=0.2, h=0.2, kappa=5.0/6.0):
    """Exact Mindlin (first-order shear) centre deflection of the SSSS plate,
    double-sine series with per-harmonic shear amplification
    (1 + D*(alpha^2+beta^2)/(kappa*G*h)). Kirchhoff limit is kappa -> inf."""
    D = E * h**3 / (12.0 * (1.0 - nu**2))
    G = E / (2.0 * (1.0 + nu))
    w = 0.0
    for m in range(1, 80, 2):
        for n in range(1, 80, 2):
            al, be = m * np.pi / a, n * np.pi / a
            wk = 16.0 * q / (np.pi**2 * D * m * n * (al * al + be * be)**2)
            w += wk * (1.0 + D * (al * al + be * be) / (kappa * G * h)) \
                 * np.sin(al * a / 2) * np.sin(be * a / 2)
    return w


